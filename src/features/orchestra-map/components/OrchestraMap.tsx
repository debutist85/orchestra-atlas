// Shortest time the launch count may take to reach 100, so it reads as a
// count rather than a flash when everything is already cached.
const LAUNCH_COUNT_MS = 1000
const INVITATION_COPY = {
  primary: 'Play the orchestra',
  secondary: 'or select a group to explore',
}
// A single "no interaction" delay governs both the first idle kick-in and
// every resume after hover/click, so the behavior reads as one consistent
// rule rather than two different timings for first-run vs. resume.
const IDLE_HIGHLIGHT_TIMING = { delaySeconds: 1.4, stepSeconds: 1.4 }

// Small (-sm.webp) variants are generated by `npm run images:resize`, which
// also writes artwork-dimensions.json — so small viewports download a
// fraction of the full-resolution artwork instead of the same file desktop
// gets. `sizes` reuses the figure's CSS width when that width is a real
// length. A width of `auto` (height-only art direction) must not be passed
// through: `sizes="auto"` resolves to the 300px default image width, and
// `object-fit: contain` then letterboxes the artwork inside that narrow box.
function artworkSrcSet(src: string) {
  const fileName = src.split('/').pop()
  const dims = fileName ? (artworkDimensions as Record<string, { natural: number; small: number }>)[fileName] : undefined
  if (!dims) return undefined
  return `${src.replace(/\.webp$/, '-sm.webp')} ${dims.small}w, ${src} ${dims.natural}w`
}

function artworkSizes(width: string | undefined) {
  return width && width !== 'auto' ? width : undefined
}

function IdentityFigure({ state }: Readonly<{ state: NavigationState }>) {
  const { landscape, portrait } = identityFigures(state)
  if (!landscape && !portrait) return null
  const orientation = landscape && portrait ? undefined : landscape ? 'landscape' : 'portrait'
  const primary = (landscape ?? portrait)!
  const image = (
    <img
      className={orientation ? `map-identity-figure map-identity-figure--${orientation}` : 'map-identity-figure'}
      src={primary.src}
      srcSet={artworkSrcSet(primary.src)}
      sizes={artworkSizes(primary.width)}
      alt=""
      aria-hidden="true"
      decoding="async"
    />
  )
  // One element only. Orientation changes the CSS variables, and a portrait
  // source swaps the file when the two orientations use different assets.
  if (!landscape || !portrait || landscape.src === portrait.src) return image
  return (
    <picture>
      <source media="(orientation: portrait)" srcSet={artworkSrcSet(portrait.src)} sizes={artworkSizes(portrait.width)} />
      {image}
    </picture>
  )
}

function readInitialSettings() {
  const search = new URLSearchParams(window.location.search)
  return {
    debug: import.meta.env.DEV && search.get('debug') === 'true',
    // Deliberately not DEV-gated, unlike `debug` above: this only reveals the
    // read-only listening diagnostics text, not the dev-tools panel or the
    // scene's debug geometry, so it's safe to use for on-device production
    // troubleshooting (e.g. ?debug=true on a phone/tablet with no devtools
    // access) without exposing the scene-debugging controls.
    listeningDebug: search.get('debug') === 'true',
  }
}

